"""KEEL letter scenes for build_pack.py shots: each letter in the signature block of one of the
pack's structures, in front of a flat wall. Every layout is shot twice, on a lime and on a
magenta wall, so the letters can be cut out by difference (icon_cut.py)."""
from pathlib import Path

FONT = {
    "K": ["X..X", "X.X.", "XX..", "X.X.", "X..X"],
    "E": ["XXX", "X..", "XX.", "X..", "XXX"],
    "L": ["X..", "X..", "X..", "X..", "XXX"],
}
# stronghold, mineshaft, desert temple, ocean monument
BLOCKS = ["mossy_stone_bricks", "oak_planks", "cut_sandstone", "prismarine_bricks"]
WALLS = {"lime": "lime_concrete", "magenta": "magenta_concrete"}
DEPTH = 3
LAYOUTS = {
    "row": (0, [("K", 0, 0), ("E", 5, 0), ("E", 9, 0), ("L", 13, 0)], 16, 5),
    "grid": (100, [("K", 0, 6), ("E", 5, 6), ("E", 0, 0), ("L", 5, 0)], 8, 11),
}
OY = 260  # above the clouds (y 192), which would pass in front of the camera
HERE = Path(__file__).parent


def scene(ox: int, layout: list, w: int, h: int, wall: str) -> list[str]:
    cmds = [f"fill {ox - 6} {OY - 6} -3 {ox + w + 6} {OY + h + 6} 27 minecraft:air",
            f"fill {ox - 70} {OY - 40} -4 {ox + w + 70} {OY + h + 30} -4 minecraft:{wall}"]
    for i, (ch, dx, dy) in enumerate(layout):
        rows = FONT[ch]
        for r, row in enumerate(rows):
            for c, px in enumerate(row):
                if px == "X":
                    x, y = ox + dx + c, OY + dy + len(rows) - 1 - r
                    cmds.append(f"fill {x} {y} 0 {x} {y} {DEPTH - 1} minecraft:{BLOCKS[i]}")
    cx, cy = ox + w / 2, OY + h / 2
    # below and to the left, so the side and bottom faces give the letters volume
    cam = (cx - 0.3 * w - 2, cy - 0.3 * h - 3, DEPTH + max(w, h) * 1.25 + 4, cx, cy, DEPTH - 1)
    cmds.append("camera " + " ".join(f"{v:.2f}" for v in cam))
    return cmds


if __name__ == "__main__":
    for name, (ox, layout, w, h) in LAYOUTS.items():
        for color, wall in WALLS.items():
            (HERE / f"keel-{name}-{color}.txt").write_text(
                "# generated by make_keel.py\n" + "\n".join(scene(ox, layout, w, h, wall)) + "\n")
